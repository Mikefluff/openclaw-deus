const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

function writeFile(workspaceRoot, relativePath, content) {
  const fullPath = path.join(workspaceRoot, relativePath);
  fs.mkdirSync(path.dirname(fullPath), { recursive: true });
  fs.writeFileSync(fullPath, content);
}

function createBeliefsFixture() {
  return (
    ["I1", "I2", "I3", "I4", "I5"]
      .map((beliefId, index) =>
        JSON.stringify({
          belief_id: beliefId,
          content: `Fixture belief ${beliefId}`,
          confidence: 1,
          source_type: "axiom",
          timestamp_created: `2026-03-0${index + 1}T00:00:00.000Z`,
        }),
      )
      .join("\n") + "\n"
  );
}

