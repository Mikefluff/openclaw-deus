"use strict";

const { getDailyMemorySections } = require("./daily-memory-schema");

const LEGACY_DAILY_MEMORY_SECTION_MAP = {
  Events: {
    section: "System Events",
    prefix: "",
  },
  "Durable observations": {
    section: "System Events",
    prefix: "Legacy durable observation: ",
  },
  "Open tensions": {
    section: "System Events",
    prefix: "Legacy open tension: ",
  },
  "Agent Memory Reflection": {
    section: "System Events",
    prefix: "Legacy memory reflection: ",
  },
};

function parseDailyMemorySections(content) {
  const sections = new Map();
  const parts = content.split(/^## /m);

  for (const part of parts.slice(1)) {
    const newlineIndex = part.indexOf("\n");
    if (newlineIndex === -1) {
      continue;
    }

    const section = part.slice(0, newlineIndex).trim();
    const body = part
      .slice(newlineIndex + 1)
      .replace(/\n---\n\*Auto-generated by DEUS memory manager\*[\s\S]*$/, "")
      .trimEnd();

    sections.set(section, body);
  }

  return sections;
}

function mergeDailyMemorySectionBodies(existingBody, incomingBody) {
  const existing = existingBody.trimEnd();
  const incoming = incomingBody.trimEnd();

  if (!existing) {
    return incoming;
  }

  if (!incoming) {
    return existing;
  }

  return `${existing}\n${incoming}`;
}

function flattenLegacyMemoryText(text) {
  return text
    .replace(/^\s*-\s*/, "")
    .replace(/\s*\n\s*/g, " ")
    .trim();
}

function splitLegacyBlocks(trimmed) {
  return trimmed.split(/\n\s*\n/);
}

function splitDailyMemoryEntryBlocks(sectionBody) {
  const blocks = [];
  let current = [];

  for (const line of sectionBody.split("\n")) {
    if (line.startsWith("- ")) {
      if (current.length > 0) {
        blocks.push(current.join("\n").trimEnd());
      }
      current = [line];
      continue;
    }

    if (current.length > 0) {
      current.push(line);
    }
  }

  if (current.length > 0) {
    blocks.push(current.join("\n").trimEnd());
  }

  return blocks.filter(Boolean);
}

function migrateLegacyBodyToBullets(body, prefix = "") {
  const trimmed = body.trim();
  if (!trimmed) {
    return "";
  }

  const entryBlocks = splitDailyMemoryEntryBlocks(trimmed);
  if (entryBlocks.length > 0) {
    return entryBlocks
      .map((block) => flattenLegacyMemoryText(block))
      .filter(Boolean)
      .map((line) => `- ${prefix}${line}`)
      .join("\n");
  }

  return splitLegacyBlocks(trimmed)
    .map((block) => flattenLegacyMemoryText(block))
    .filter(Boolean)
    .map((line) => `- ${prefix}${line}`)
    .join("\n");
}

function extractLooseDailyMemoryBody(content) {
  let remainder = content.replace(/^# .+\n+/, "");
  remainder = remainder.replace(/^\*\*Total activities:\*\*.*(?:\n+|$)/m, "");
  remainder = remainder.split(/^## /m)[0];
  remainder = remainder.replace(
    /\n?---\n\*Auto-generated by DEUS memory manager\*\n?$/m,
    "",
  );

  return remainder.trim();
}

function coerceToCanonicalDailyMemorySections(content, options = {}) {
  const rawSections = parseDailyMemorySections(content);
  const canonicalSections = new Map();
  const dailySections = getDailyMemorySections(options);
  const looseBody = extractLooseDailyMemoryBody(content);

  if (looseBody) {
    canonicalSections.set(
      "System Events",
      migrateLegacyBodyToBullets(looseBody),
    );
  }

  for (const [section, body] of rawSections.entries()) {
    if (dailySections.includes(section)) {
      canonicalSections.set(
        section,
        mergeDailyMemorySectionBodies(
          canonicalSections.get(section) || "",
          body,
        ),
      );
      continue;
    }

    const legacyMapping = LEGACY_DAILY_MEMORY_SECTION_MAP[section] || {
      section: "System Events",
      prefix: `Legacy ${section}: `,
    };
    const migratedBody = migrateLegacyBodyToBullets(body, legacyMapping.prefix);

    if (!migratedBody) {
      continue;
    }

    canonicalSections.set(
      legacyMapping.section,
      mergeDailyMemorySectionBodies(
        canonicalSections.get(legacyMapping.section) || "",
        migratedBody,
      ),
    );
  }

  return canonicalSections;
}

module.exports = {
  LEGACY_DAILY_MEMORY_SECTION_MAP,
  coerceToCanonicalDailyMemorySections,
  extractLooseDailyMemoryBody,
  mergeDailyMemorySectionBodies,
  migrateLegacyBodyToBullets,
  parseDailyMemorySections,
  splitDailyMemoryEntryBlocks,
};
