const { getHumanInteractionSectionTitle } = require("./user-context");

const DAILY_MEMORY_TITLE_SUFFIX = "DEUS Activity Log";
const DAILY_MEMORY_TOTAL_ACTIVITIES_LABEL = "Total activities";

function getDailyMemorySections(options = {}) {
  return [
    "Git Activity",
    "Commands Executed",
    "Decisions",
    getHumanInteractionSectionTitle(options),
    "System Events",
  ];
}

const DAILY_MEMORY_SECTIONS = getDailyMemorySections();
const DAILY_MEMORY_FOOTER = "---\n*Auto-generated by DEUS memory manager*\n";

function findMissingDailyMemorySections(content, options = {}) {
  return getDailyMemorySections(options).filter(
    (section) => !content.includes(`## ${section}`),
  );
}

module.exports = {
  DAILY_MEMORY_FOOTER,
  DAILY_MEMORY_SECTIONS,
  DAILY_MEMORY_TITLE_SUFFIX,
  DAILY_MEMORY_TOTAL_ACTIVITIES_LABEL,
  getDailyMemorySections,
  findMissingDailyMemorySections,
};
